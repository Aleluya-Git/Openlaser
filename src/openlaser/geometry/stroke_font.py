_ACCENTS = str.maketrans("ÁÉÍÓÚÜÑÇáéíóúüñç", "AEIOUUNCAEIOUUNC")


def supported(ch: str) -> bool:
    c = ch.upper().translate(_ACCENTS)
    return c == " " or c in _GLYPHS


def text_width(text: str, height: float) -> float:
    if not text:
        return 0.0
    k = height / _H
    return (len(text) * _ADVANCE - (_ADVANCE - _W)) * k


def text_subpaths(text: str, x: float, y: float, height: float, anchor: str = "left") -> list[gp.SubPath]:
    """Texto con la línea base en ``y``. ``anchor``: left | center | right. Caracteres desconocidos → «?»."""
    k = height / _H
    w = text_width(text, height)
    x0 = x - (w / 2 if anchor == "center" else w if anchor == "right" else 0.0)
    out: list[gp.SubPath] = []
    for i, ch in enumerate(text):
        c = ch.upper().translate(_ACCENTS)
        if c == " ":
            continue
        strokes = _GLYPHS.get(c, _GLYPHS["?"])
        ox = x0 + i * _ADVANCE * k
        for stroke in strokes:
            pts = [(ox + px * k, y - height + py * k) for px, py in stroke]
            closed = len(pts) > 2 and pts[0] == pts[-1]
            out.append(gp.polyline(pts[:-1] if closed else pts, closed))
    return out
